const EQUITY_ROLE_IDS = new Set([
  'owner', 'member', 'shareholder', 'gp', 'lp',
  'joint_tenant', 'tenant_in_common', 'community_property',
]);
const ROLE_LABEL = new Map(ROLE_OPTIONS.map((r) => [r.id, r.label]));

const fmtDate = (d = new Date()) =>
  d.toLocaleDateString(undefined, { year: 'numeric', month: 'long', day: 'numeric' });

export default function EntitiesPrintPage() {
  const { estateId } = useParams();
  const navigate = useNavigate();
  const { user, getAuthHeaders } = useAuth();
  const [data, setData] = useState(null);
  const [beneficiaries, setBeneficiaries] = useState([]);
  const [estateName, setEstateName] = useState('');
  const [error, setError] = useState(null);

  // Fetch the chart payload (entities + people + relationships +
  // server-persisted overrides), the beneficiaries list (so spouse /
  // children / other named beneficiaries that participate in
  // relationships render as person tiles — exactly like the live
  // chart does), plus the estate name for the header.
  useEffect(() => {
    let alive = true;
    (async () => {
      try {
        const headers = getAuthHeaders();
        const [entitiesRes, estateRes, bensRes] = await Promise.all([
          axios.get(`${API_URL}/financial/entities/${estateId}`, headers),
          axios.get(`${API_URL}/estates/${estateId}`, headers).catch(() => ({ data: null })),
          axios.get(`${API_URL}/beneficiaries/${estateId}`, headers).catch(() => ({ data: [] })),
        ]);
        if (!alive) return;
        setData(entitiesRes.data || {});
        setBeneficiaries(Array.isArray(bensRes?.data) ? bensRes.data : []);
        setEstateName(estateRes?.data?.name || '');
      } catch (e) {
        if (!alive) return;
        setError(e?.response?.data?.detail || e?.message || 'Could not load chart data');
      }
    })();
    return () => { alive = false; };
  }, [estateId, getAuthHeaders]);

  // Compute layout + bbox once data lands.
  const layout = useMemo(() => {
    if (!data) return null;
    const graph = buildGraph({
      entities: data.entities || [],
      externals: data.external_people || [],
      relationships: data.relationships || [],
      beneficiaries,
      blocks: data.beneficiary_blocks || [],
      user,
    });
    const initial = computeInitialLayout(graph.nodes, graph.depth);
    const overrides = data.chart_layout || {};

    const positionOf = (key) => overrides[key] || initial.positions[key] || { x: 0, y: 0 };

    // Tile rects (real nodes + legend pseudo-tile so edges avoid it
    // and the bbox includes it).
    const tileRects = graph.nodes.map((n) => {
      const p = positionOf(n.key);
      return {
        key: n.key,
        x: p.x,
        y: p.y,
        w: n.w,
        h: n.h,
        node: n,
      };
    });

    // Compute the legend's REAL height the same way renderLegend()
    // does. The static LEGEND_H constant assumed a max-size legend —
    // when fewer roles/categories are present, the legend is shorter,
    // and conversely with many roles+categories it can exceed
    // LEGEND_H. Using the wrong height starves the bbox of vertical
    // room and clips the legend in the printed PDF.
    const headerH = 22;
    const rowH = 18;
    const presentRoleIds = new Set();
    (data.relationships || []).forEach((r) => { if (r.role) presentRoleIds.add(r.role); });
    const presentRolesCount = ROLE_OPTIONS.filter((r) => presentRoleIds.has(r.id)).length;
    const presentCategoryIds = new Set();
    (data.entities || []).forEach((e) => { if (e.category) presentCategoryIds.add(e.category); });
    const presentCategoriesCount = (ENTITY_BUCKETS || []).filter((b) => presentCategoryIds.has(b.id)).length;
    const nLegendRows = presentRolesCount + presentCategoriesCount + ((presentRolesCount && presentCategoriesCount) ? 1 : 0);
    const computedLegendH = Math.max(60, headerH + nLegendRows * rowH + 14);

    // Honor the user's saved legend position from the live chart —
    // they drag it where they want; the print just inherits the same
    // coordinates. Since the legend is rendered INSIDE the tree SVG,
    // the whole composition scales together via preserveAspectRatio.
    const legendPos = overrides.__legend__ || { x: -LEGEND_W - 24, y: 0 };
    tileRects.push({ key: '__legend__', x: legendPos.x, y: legendPos.y, w: LEGEND_W, h: computedLegendH });

    // Pre-route every edge so we can fold the routed polyline points
    // and the ownership-% badge box into the bbox. Edge routing
    // detours around obstacles via `hit.y + hit.h + 14` style jumps —
    // those bend points can extend FAR outside any single tile, so
    // bbox'ing tiles alone leaves edges (and their %-pills) clipped
    // in the printed PDF.
    const rectByKey = Object.fromEntries(tileRects.map((r) => [r.key, r]));

    const routedEdges = graph.edges.map((edge) => {
      const sR = rectByKey[edge.sourceKey];
      const tR = rectByKey[edge.targetKey];
      if (!sR || !tR) return null;
      const obstacles = tileRects.filter((r) => r.key !== sR.key && r.key !== tR.key);
      const { points, midPoint } = routeEdge(sR, tR, obstacles, edge.id);
      return { edge, points, midPoint };
    }).filter(Boolean);

    // BBox covering every tile + every routed edge point + every
    // ownership label box + a comfortable padding so strokes/labels
    // never clip at the edges of the SVG viewBox.
    const PAD = 32;
    let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
    const extend = (x, y) => {
      if (x < minX) minX = x;
      if (y < minY) minY = y;
      if (x > maxX) maxX = x;
      if (y > maxY) maxY = y;
    };
    tileRects.forEach((r) => {
      extend(r.x, r.y);
      extend(r.x + r.w, r.y + r.h);
    });
    routedEdges.forEach(({ edge, points, midPoint }) => {
      points.forEach((p) => extend(p.x, p.y));
      // Ownership % pill: 36×18 centered on midPoint.
      if (EQUITY_ROLE_IDS.has(edge.role) && edge.ownership_pct != null) {
        extend(midPoint.x - 18, midPoint.y - 9);
        extend(midPoint.x + 18, midPoint.y + 9);
      }
    });
    if (!isFinite(minX)) { minX = minY = 0; maxX = 800; maxY = 600; }

    const viewBox = {
      x: minX - PAD,
      y: minY - PAD,
      w: (maxX - minX) + 2 * PAD,
      h: (maxY - minY) + 2 * PAD,
    };

    // 12pt minimum print font enforcement.
    // The page SVG is 7.9in × 8.2in. At 96 dpi that's 790 × 820 CSS-px,
    // which is also our outer viewBox. We then transform the inner
    // <g> by `scale(s)` where s = min(PAGE_W/bbox.w, PAGE_H/bbox.h).
    // Inside that transform, 1 user-unit prints at:
    //   user-unit-px = s × (7.9in / 790) = s × 0.01 in = s × 0.72 pt
    // To guarantee 12 pt minimum printed text, fontSize in user-units
    // must be ≥ 12 / (s × 0.72) ≈ 16 / s.
    // We pre-compute that here and ship it in the layout object so
    // every text element wraps its hard-coded fontSize in
    // Math.max(N, minFont). Tiles that don't shrink (s≥1) get the
    // raw 16 floor (12pt native at 1:1 scale).
    const PAGE_W = 790;
    const PAGE_H = 820;
    const s = Math.min(PAGE_W / Math.max(viewBox.w, 1), PAGE_H / Math.max(viewBox.h, 1));
    const minFont = Math.ceil(16 / Math.max(s, 0.01));

    return {
      nodes: graph.nodes,
      edges: graph.edges,
      routedEdges,
      tileRects,
      legendPos,
      computedLegendH,
      viewBox,
      minFont,
      relationships: data.relationships || [],
      entities: data.entities || [],
      blocks: data.beneficiary_blocks || [],
    };
  }, [data, user, beneficiaries]);

  // No auto-print: iOS Safari blocks programmatic window.print() that
  // isn't a direct response to a user tap, and re-rendering on memo
  // changes causes the "blocked from automatically printing" dialog
  // to re-pop forever. The user invokes printing via the Print chip
  // in the on-screen toolbar — that click IS a user gesture, so iOS
  // shows the share-sheet print UI cleanly with no warning.

  if (error) {
    return (
      <div style={{ padding: 32, fontFamily: 'system-ui, -apple-system, sans-serif', color: '#0f172a', background: '#ffffff', minHeight: '100vh' }}>
        <button
          type="button"
          onClick={() => navigate(-1)}
          style={{
            display: 'inline-flex', alignItems: 'center', gap: 6,
            padding: '8px 14px', borderRadius: 9999,
            border: '1px solid #B8860B', background: '#fffaf0',
            color: '#B8860B', fontSize: 13, fontWeight: 700, cursor: 'pointer',
            marginBottom: 16,
          }}
          data-testid="entity-print-back"
        >
          <ChevronLeft size={14} /> Back
        </button>
        <h1 style={{ marginTop: 0, fontSize: 20 }}>Could not generate print</h1>
        <p>{error}</p>
      </div>
    );
  }
  if (!layout) {
    return (
      <div style={{ padding: 32, fontFamily: 'system-ui, -apple-system, sans-serif', color: '#0f172a', background: '#ffffff', minHeight: '100vh' }}>
        <button
          type="button"
          onClick={() => navigate(-1)}
          style={{
            display: 'inline-flex', alignItems: 'center', gap: 6,
            padding: '8px 14px', borderRadius: 9999,
            border: '1px solid #B8860B', background: '#fffaf0',
            color: '#B8860B', fontSize: 13, fontWeight: 700, cursor: 'pointer',
            marginBottom: 16,
          }}
          data-testid="entity-print-back"
        >
          <ChevronLeft size={14} /> Back
        </button>
        Loading chart for printing…
      </div>
    );
  }

  const today = fmtDate();
  const presentRoles = (() => {
    const seen = new Set();
    layout.relationships.forEach((r) => { if (r.role) seen.add(r.role); });
    return ROLE_OPTIONS.filter((r) => seen.has(r.id));
  })();
  const presentCategories = (() => {
    const seen = new Set();
    layout.entities.forEach((e) => { if (e.category) seen.add(e.category); });
    return (ENTITY_BUCKETS || []).filter((b) => seen.has(b.id));
  })();

  // ── Static SVG renderer ──────────────────────────────────────────

  // 12pt minimum-font helper. Every hard-coded fontSize in the SVG
  // below is wrapped in `mf(N)` so it can be bumped up by the layout
  // memo when the chart shrinks to fit a single page (per user's
  // strict "no less than 12pt in any text PDFs" rule).
  const mf = (n) => Math.max(n, layout.minFont);

  const renderEdges = () => {
    return layout.routedEdges.map(({ edge, points, midPoint }) => {
      const role = ROLE_PALETTE[edge.role] || ROLE_PALETTE.owner;
      const isEquity = EQUITY_ROLE_IDS.has(edge.role);
      const stroke = isEquity ? '#B8860B' : role.color;
      const sw = isEquity && edge.ownership_pct ? Math.max(1.6, Math.min(3.4, edge.ownership_pct / 33)) : 1.8;
      const d = polylineToRoundedPath(points);
      return (
        <g key={edge.id}>
          <path
            d={d}
            fill="none"
            stroke={stroke}
            strokeWidth={sw}
            strokeLinecap="round"
            strokeLinejoin="round"
            strokeDasharray={role.dash || undefined}
            opacity={0.95}
          />
          {isEquity && edge.ownership_pct != null && (
            <g transform={`translate(${midPoint.x - 18}, ${midPoint.y - 9})`}>
              <rect width="36" height="18" rx="9" fill="#fffaf0" stroke="#B8860B" strokeWidth="1" />
              <text x="18" y="13" textAnchor="middle" fontSize={mf(10)} fontWeight="700" fill="#B8860B">
                {Math.round(edge.ownership_pct)}%
              </text>
            </g>
          )}
        </g>
      );
    });
  };

  const renderTile = (rect) => {
    const n = rect.node;
    if (!n) return null;
    const isEntity = n.kind === 'entity';
    const isCluster = n.kind === 'cluster';
    const e = isEntity ? n.entity : null;
    const typeMeta = isEntity ? getTypeMeta(e.category, e.type) : null;
    const titleText = isEntity ? (e?.name || 'Entity') : (n.label || '');
    const subText = isEntity
      ? (typeMeta?.friendly || e?.type || '')
      : (n.sublabel || '');
    // Pull category palette + bucket meta from the live entity
    // catalog so the print SVG inherits the same color coding the
    // user sees on the platform (steel/indigo/champagne/teal/slate).
    const entityPalette = isEntity ? getEntityPalette(e) : null;
    const bucketMeta = isEntity ? getBucketMeta(e?.category) : null;
    const accentColor = entityPalette?.stroke || '#B8860B';
    const tileFill = '#FFFFFF';
    // Person tiles keep the soft gold border (matches platform).
    // Entity tiles get the bucket's accent color so business/trust/
    // charity/etc. are visually distinct at a glance.
    const tileStroke = isEntity ? accentColor : '#B8860B';
    const tileStrokeW = 1.3;
    const avatarColor = n.avatar_color || '#B8860B';
    const avatarBg = n.kind === 'user' ? '#FEF3C7' : '#FFFFFF';
    const photoUrl = !isCluster ? (n.photo || null) : null;
    const clipId = `print-avatar-clip-${n.key.replace(/[^a-zA-Z0-9]/g, '_')}`;
    const iconPaths = isEntity ? BUCKET_ICON_PATHS[bucketMeta?.id || 'specialized'] : null;
    return (
      <g key={n.key} transform={`translate(${rect.x}, ${rect.y})`}>
        {/* Tile background — entities only. Person tiles render
            borderless (just the avatar circle + name + role) so the
            print page matches the live chart, where people float on
            the canvas without a surrounding card. */}
        {isEntity && (
          <rect
            width={rect.w}
            height={rect.h}
            rx={CORNER_R}
            fill={tileFill}
            stroke={tileStroke}
            strokeWidth={tileStrokeW}
          />
        )}
        {/* Entity tile: Lucide bucket icon (left), then title + sub */}
        {isEntity && (
          <>
            {iconPaths && (
              <g
                transform={`translate(8, ${rect.h / 2 - 10}) scale(0.83)`}
                fill="none"
                stroke={accentColor}
                strokeWidth={2}
                strokeLinecap="round"
                strokeLinejoin="round"
              >
                {iconPaths}
              </g>
            )}
            <text
              x={36}
              y={rect.h / 2 - 4}
              fontSize={mf(13)}
              fontWeight="700"
              fill="#0F172A"
            >
              {truncate(titleText, 24)}
            </text>
            {subText && (
              <text
                x={36}
                y={rect.h / 2 + 12}
                fontSize={mf(10)}
                fontWeight="600"
                fill={accentColor}
              >
                {truncate(subText, 28)}
              </text>
            )}
            {e?.formation_state && (
              <g transform={`translate(${36}, ${rect.h - 18})`}>
                <rect width="28" height="13" rx="6" fill="#FFFAF0" stroke={accentColor} strokeWidth={0.9} />
                <text x="14" y="9.5" textAnchor="middle" fontSize={mf(8)} fontWeight="700" fill={accentColor}>
                  {e.formation_state}
                </text>
              </g>
            )}
          </>
        )}
        {/* Cluster tile — composite box rendering every beneficiary
            of the parent entity as a half-size avatar (5 per row,
            staggered). Connected to the parent entity by a single
            line in the edge layer. */}
        {isCluster && (() => {
          const members = n.members || [];
          const CLUSTER_AVATAR_R = 16;
          const CLUSTER_SLOT_W = 50;
          const CLUSTER_SLOT_H = 60;
          const CLUSTER_COLS = 5;
          const CLUSTER_HEADER_H = 22;
          const CLUSTER_PAD_X = 10;
          const CLUSTER_PAD_Y = 8;
          const HALF_STEP = CLUSTER_SLOT_W / 2;
          const parentName = (data.entities || []).find((ent) => ent.id === n.id)?.name || '';
          return (
            <>
              <rect
                width={rect.w}
                height={rect.h}
                rx={CORNER_R}
                fill="#F0FDF9"
                stroke="#22C993"
                strokeWidth={1.3}
              />
              <text
                x={CLUSTER_PAD_X}
                y={14}
                fontSize={mf(9)}
                fontWeight="700"
                fill="#0F766E"
                style={{ textTransform: 'uppercase' }}
              >
                {`${members.length} beneficiar${members.length === 1 ? 'y' : 'ies'} · ${parentName}`.slice(0, 40)}
              </text>
              {members.map((m, i) => {
                const row = Math.floor(i / CLUSTER_COLS);
                const col = i % CLUSTER_COLS;
                const stagger = row % 2 === 1 ? HALF_STEP : 0;
                const slotX = CLUSTER_PAD_X + col * CLUSTER_SLOT_W + stagger;
                const slotY = CLUSTER_HEADER_H + CLUSTER_PAD_Y + row * CLUSTER_SLOT_H;
                const cx = slotX + CLUSTER_AVATAR_R + 2;
                const cy = slotY + CLUSTER_AVATAR_R + 2;
                const memberClip = `print-cluster-clip-${n.id}-${m.id}`;
                const initials = (m.first_name?.[0] || '?').toUpperCase();
                return (
                  <g key={m.id}>
                    <defs>
                      <clipPath id={memberClip}>
                        <circle cx={cx} cy={cy} r={CLUSTER_AVATAR_R - 1} />
                      </clipPath>
                    </defs>
                    <circle cx={cx} cy={cy} r={CLUSTER_AVATAR_R} fill="#FFFFFF" stroke={m.avatar_color || '#22C993'} strokeWidth={1.3} />
                    {m.photo ? (
                      <image
                        href={m.photo}
                        xlinkHref={m.photo}
                        x={cx - CLUSTER_AVATAR_R + 1}
                        y={cy - CLUSTER_AVATAR_R + 1}
                        width={(CLUSTER_AVATAR_R - 1) * 2}
                        height={(CLUSTER_AVATAR_R - 1) * 2}
                        preserveAspectRatio="xMidYMid slice"
                        clipPath={`url(#${memberClip})`}
                      />
                    ) : (
                      <text x={cx} y={cy + 4} textAnchor="middle" fontSize={mf(10)} fontWeight="700" fill="#0F766E">
                        {initials}
                      </text>
                    )}
                    <text
                      x={cx}
                      y={cy + CLUSTER_AVATAR_R + 10}
                      textAnchor="middle"
                      fontSize={mf(8)}
                      fontWeight="700"
                      fill="#0F172A"
                    >
                      {truncate((m.first_name || '').split(' ')[0], 8)}
                    </text>
                  </g>
                );
              })}
            </>
          );
        })()}
        {/* Person tile: avatar circle (with photo if present) + name + sub + role chips. */}
        {!isEntity && !isCluster && (
          <>
            <defs>
              <clipPath id={clipId}>
                <circle cx={rect.w / 2} cy={28} r={22} />
              </clipPath>
            </defs>
            {/* Avatar ring */}
            <circle
              cx={rect.w / 2}
              cy={28}
              r={23}
              fill={avatarBg}
              stroke={avatarColor}
              strokeWidth={1.8}
            />
            {photoUrl ? (
              <image
                href={photoUrl}
                xlinkHref={photoUrl}
                x={rect.w / 2 - 22}
                y={6}
                width={44}
                height={44}
                preserveAspectRatio="xMidYMid slice"
                clipPath={`url(#${clipId})`}
              />
            ) : (
              <text
                x={rect.w / 2}
                y={33}
                textAnchor="middle"
                fontSize={mf(14)}
                fontWeight="700"
                fill="#92400E"
              >
                {((n.label?.[0] || '') + (n.sublabel?.[0] || '')).toUpperCase().slice(0, 2)}
              </text>
            )}
            {/* Name */}
            <text
              x={rect.w / 2}
              y={68}
              textAnchor="middle"
              fontSize={mf(11)}
              fontWeight="700"
              fill="#0F172A"
            >
              {truncate(titleText, 14)}
            </text>
            {subText && (
              <text
                x={rect.w / 2}
                y={82}
                textAnchor="middle"
                fontSize={mf(9)}
                fill="#475569"
              >
                {truncate(subText, 16)}
              </text>
            )}
            {Array.isArray(n.titles) && n.titles.length > 0 && (
              <text
                x={rect.w / 2}
                y={98}
                textAnchor="middle"
                fontSize={mf(9)}
                fontWeight="700"
                fill={tileStroke}
              >
                {truncate(n.titles.join(' · '), 18)}
              </text>
            )}
          </>
        )}
      </g>
    );
  };

  // Legend rendered INSIDE the main tree SVG at the user's saved
  // drag position from the live chart. Because it's part of the same
  // SVG that gets scaled to fit the page (via preserveAspectRatio),
  // it always renders in the right place at the right size — no
  // separate absolute-positioning math needed.
  const renderLegend = () => {
    if (presentRoles.length === 0 && presentCategories.length === 0) return null;
    const lp = layout.legendPos;
    const headerH = 22;
    const rowH = 18;
    // Use the SAME computed height we baked into the bbox so the
    // legend always fits inside the SVG viewBox (no clipping).
    const computedH = layout.computedLegendH;
    return (
      <g transform={`translate(${lp.x}, ${lp.y})`}>
        <rect
          width={LEGEND_W}
          height={computedH}
          rx={12}
          fill="#ffffff"
          stroke="#B8860B"
          strokeWidth={1.4}
        />
        <text x={10} y={16} fontSize={mf(11)} fontWeight="700" fill="#B8860B" letterSpacing="0.06em">
          LEGEND
        </text>
        <line x1={0} x2={LEGEND_W} y1={headerH} y2={headerH} stroke="#B8860B" strokeOpacity={0.35} />
        {presentRoles.map((role, i) => {
          const palette = ROLE_PALETTE[role.id] || ROLE_PALETTE.owner;
          const isEquity = EQUITY_ROLE_IDS.has(role.id);
          const stroke = isEquity ? '#B8860B' : palette.color;
          const y = headerH + 14 + i * rowH;
          return (
            <g key={role.id}>
              <line
                x1={10} x2={42}
                y1={y - 3} y2={y - 3}
                stroke={stroke}
                strokeWidth={isEquity ? 2.2 : 1.8}
                strokeLinecap="round"
                strokeDasharray={palette.dash || undefined}
              />
              <text x={50} y={y} fontSize={mf(11)} fill="#0f172a">{role.label}</text>
            </g>
          );
        })}
        {presentRoles.length > 0 && presentCategories.length > 0 && (
          <line
            x1={6} x2={LEGEND_W - 6}
            y1={headerH + 8 + presentRoles.length * rowH}
            y2={headerH + 8 + presentRoles.length * rowH}
            stroke="#B8860B"
            strokeOpacity={0.18}
          />
        )}
        {presentCategories.map((b, i) => {
          const yOffset = headerH + 14 + presentRoles.length * rowH + (presentRoles.length ? rowH : 0) + i * rowH;
          const bucketColor = (PALETTE[b.accent] || PALETTE.slate).stroke;
          const iconPaths = BUCKET_ICON_PATHS[b.id];
          return (
            <g key={b.id}>
              {iconPaths ? (
                <g
                  transform={`translate(15, ${yOffset - 14}) scale(0.55)`}
                  fill="none"
                  stroke={bucketColor}
                  strokeWidth={2}
                  strokeLinecap="round"
                  strokeLinejoin="round"
                >
                  {iconPaths}
                </g>
              ) : (
                <circle cx={26} cy={yOffset - 3} r={5} fill={bucketColor} />
              )}
              <text x={42} y={yOffset} fontSize={mf(11)} fill="#0f172a">{b.label}</text>
            </g>
          );
        })}
      </g>
    );
  };

  return ReactDOM.createPortal(
    <div className="cfp-print-root">
      <style>{`
        @page { size: letter portrait; margin: 0; }
        @media print {
          html, body {
            background: #ffffff !important;
            margin: 0 !important;
            padding: 0 !important;
            width: 8.5in !important;
            min-width: 8.5in !important;
            max-width: 8.5in !important;
            height: 10.0in !important;
            min-height: 0 !important;
            max-height: 10.0in !important;
            overflow: hidden !important;
          }
          /* The print root is rendered via React portal AS A DIRECT
             CHILD OF <body>. That lets us hide every OTHER body
             child cleanly — incl. NetworkStatusBanner, PendingSyncChip,
             NotificationContainer, and the entire #root mount — so
             nothing they render adds height to the print document. */
          body > *:not(.cfp-print-root) {
            display: none !important;
          }
          .cfp-print-root {
            color: #0f172a !important;
            display: block !important;
            position: relative !important;
            width: 8.5in !important;
            min-width: 8.5in !important;
            max-width: 8.5in !important;
            /* Sized to 8.5in × 9.5in inside an 11in page. Leaves
               ~1.5in of slack for iOS Safari's invisible "system"
               margin / its own header-footer chrome on every printed
               page — single-page output is guaranteed and the tree
               has enough vertical room to center properly between
               our header and the iOS footer. */
            height: 9.5in !important;
            min-height: 0 !important;
            max-height: 9.5in !important;
            padding: 0.3in !important;
            margin: 0 !important;
            box-sizing: border-box !important;
            overflow: hidden !important;
            page-break-inside: avoid !important;
            page-break-after: avoid !important;
            break-inside: avoid !important;
            break-after: avoid !important;
          }
          .cfp-print-root * {
            page-break-inside: avoid !important;
            page-break-after: avoid !important;
            break-inside: avoid !important;
            break-after: avoid !important;
          }
          .cfp-print-header {
            display: block !important;
            height: 0.65in !important;
            max-height: 0.65in !important;
            margin: 0 0 0.05in 0 !important;
            padding: 0 0 6px 0 !important;
            /* Override screen rule that put a 2px gold border on the
               bottom — it cut through the subtitle when squeezed into
               the print height. Use a thin gold rule INSIDE the
               header's allotted height instead. */
            border-bottom: 1px solid #B8860B !important;
            overflow: hidden !important;
          }
          .cfp-print-svg-wrap {
            display: block !important;
            width: 7.9in !important;
            /* Fills ALL the remaining vertical space below the header
               (root 9.5in - 0.6in padding - 0.65in header - 0.05in
               header bottom-margin = 8.2in). Block layout with hard
               inch sizing on BOTH wrap and SVG — iOS Safari's print
               engine honors absolute inch units but collapses
               percentage-based SVG sizing inside flex. */
            height: 8.2in !important;
            max-height: 8.2in !important;
            min-height: 8.2in !important;
            margin: 0 auto !important;
            padding: 0 !important;
            overflow: hidden !important;
            position: relative !important;
          }
          .cfp-print-svg-wrap svg {
            display: block !important;
            width: 7.9in !important;
            height: 8.2in !important;
            min-width: 7.9in !important;
            min-height: 8.2in !important;
            max-width: 7.9in !important;
            max-height: 8.2in !important;
            margin: 0 !important;
            padding: 0 !important;
          }
          /* iOS Safari automatically renders its OWN footer (URL +
             date + page number) on every printed page; hide our
             in-document footer to avoid the duplicate. */
          .cfp-print-footer { display: none !important; }
          .cfp-print-toolbar { display: none !important; }
        }
        body { background: #f4f4f4; margin: 0; }
        .cfp-print-root {
          font-family: ui-sans-serif, system-ui, -apple-system, "Segoe UI", Roboto, sans-serif;
          color: #0f172a;
          /* Fluid on small screens, capped at letter width on tablets
             and desktop so the on-screen preview matches what the
             saved PDF will look like. The @media print branch above
             pins it to the exact letter usable area. */
          width: 100%;
          max-width: 7.5in;
          /* Use dynamic-viewport-height so the layout fits the *real*
             visible area on iOS Safari/PWA (where the URL bar and
             home-indicator eat into 100vh). Falls back to 100vh for
             browsers that don't support dvh. */
          min-height: 100vh;
          min-height: 100dvh;
          height: 100vh;
          height: 100dvh;
          margin: 0 auto;
          padding: 0 12px;
          padding-bottom: max(12px, env(safe-area-inset-bottom));
          box-sizing: border-box;
          display: flex;
          flex-direction: column;
          position: relative;
          overflow: hidden;
        }
        .cfp-print-toolbar {
          display: flex;
          gap: 8px;
          padding: 12px 0;
          /* Honor the iOS notch / Dynamic-Island safe area so Back +
             Print stay tappable on every device. The :12px inner
             padding is in addition to the env() inset. */
          padding-top: max(12px, env(safe-area-inset-top));
          padding-left: max(12px, env(safe-area-inset-left));
          padding-right: max(12px, env(safe-area-inset-right));
          position: sticky;
          top: 0;
          background: #f4f4f4;
          z-index: 10;
        }
        .cfp-print-toolbar button {
          display: inline-flex; align-items: center; gap: 6px;
          padding: 8px 14px; border-radius: 9999px;
          font-size: 13px; font-weight: 700;
          cursor: pointer;
        }
        .cfp-print-back {
          background: #ffffff; color: #0f172a; border: 1px solid #cbd5e1;
        }
        .cfp-print-reprint {
          background: #fffaf0; color: #B8860B; border: 1px solid #B8860B;
        }
        .cfp-print-header {
          border-bottom: 2px solid #B8860B;
          padding-bottom: 12px;
          margin-bottom: 12px;
        }
        .cfp-print-header h1 {
          margin: 0;
          font-size: 20px;
          font-weight: 800;
          color: #B8860B;
          letter-spacing: 0.02em;
        }
        .cfp-print-header .subtitle {
          margin-top: 4px;
          font-size: 13px;
          color: #475569;
        }
        .cfp-print-svg-wrap {
          flex: 1 1 auto;
          min-height: 0;
          width: 100%;
          display: block;
          position: relative;
        }
        .cfp-print-svg-wrap svg {
          width: 100%;
          height: 100%;
          display: block;
        }
        .cfp-print-footer {
          margin-top: 12px;
          padding-top: 8px;
          border-top: 1px solid #e2e8f0;
          font-size: 10px;
          color: #94a3b8;
          display: flex;
          justify-content: space-between;
        }
      `}</style>

      {/* Screen-only toolbar — gives the user an obvious escape route
          on iOS standalone PWA where the OS print dialog cancels and
          leaves them on this page. Hidden via @media print so the
          PDF stays clean. */}
      <div className="cfp-print-toolbar">
        <button
          type="button"
          className="cfp-print-back"
          onClick={() => navigate(-1)}
          data-testid="entity-print-back"
        >
          <ChevronLeft size={14} /> Back
        </button>
        <button
          type="button"
          className="cfp-print-reprint"
          onClick={() => { try { window.print(); } catch { /* user dismissed */ } }}
          data-testid="entity-print-reprint"
        >
          <Printer size={14} /> Print
        </button>
      </div>

      <div className="cfp-print-page cfp-print-page-1">
        <div className="cfp-print-header">
          <h1>Entities &amp; Structures</h1>
          <div className="subtitle">
            {estateName ? `${estateName} • ` : ''}{today}
          </div>
        </div>

        <div className="cfp-print-svg-wrap">
          {(() => {
            // iOS Safari's print engine silently ignores `preserveAspectRatio`
            // on SVG when the surrounding wrapper has hard inch dimensions —
            // so tree content authored in user-space coordinates leaks past
            // the right/bottom edges of the page. Sidestep the engine by
            // using a FIXED pixel-unit viewBox (790×820, the rounded pixel
            // equivalent of our 7.9×8.2-inch physical SVG) and applying the
            // bbox-fit scale + center-translate ourselves on an outer <g>.
            // This makes the tree render *deterministically* at the size
            // we computed, regardless of how the browser interprets the
            // outer <svg> sizing.
            const PAGE_W = 790;
            const PAGE_H = 820;
            const bb = layout.viewBox;
            const scale = Math.min(
              PAGE_W / Math.max(bb.w, 1),
              PAGE_H / Math.max(bb.h, 1),
            );
            const tx = (PAGE_W - bb.w * scale) / 2 - bb.x * scale;
            const ty = (PAGE_H - bb.h * scale) / 2 - bb.y * scale;
            return (
              <svg
                width="7.9in"
                height="8.2in"
                viewBox={`0 0 ${PAGE_W} ${PAGE_H}`}
                preserveAspectRatio="xMidYMid meet"
                xmlns="http://www.w3.org/2000/svg"
                data-testid="entity-print-svg"
                style={{ display: 'block' }}
              >
                <g transform={`translate(${tx} ${ty}) scale(${scale})`}>
                  {renderEdges()}
                  {layout.tileRects.filter((r) => r.key !== '__legend__').map(renderTile)}
                  {renderLegend()}
                </g>
              </svg>
            );
          })()}
        </div>

        <div className="cfp-print-footer">
          <span>Generated by CarryOn™</span>
          <span>carryon.us</span>
        </div>
      </div>

      {/* Page 2+ — Beneficiary Blocks summary list. Only renders when
          the estate has at least one block. Flows naturally across
          additional pages if the list is long. Every text element on
          this page is set to ≥ 12pt per the user's "no less than 12
          point font anywhere in any text PDFs" requirement. */}
      {(layout.blocks || []).length > 0 && (
        <div className="cfp-print-page cfp-print-page-2" data-testid="entity-print-blocks-page">
          <div className="cfp-print-header">
            <h1>Beneficiary Blocks</h1>
            <div className="subtitle">
              {estateName ? `${estateName} • ` : ''}{today} • {(layout.blocks || []).length} block{(layout.blocks || []).length === 1 ? '' : 's'}
            </div>
          </div>
          <div className="cfp-print-blocks-list">
            {(layout.blocks || []).map((b) => {
              const attachedEntityNames = (layout.relationships || [])
                .filter((r) => r.source_type === 'beneficiary_block'
                  && r.source_id === b.id
                  && r.target_type === 'entity'
                  && r.role === 'beneficiary')
                .map((r) => (layout.entities || []).find((e) => e.id === r.target_id)?.name)
                .filter(Boolean);
              const memberLabels = (b.members || []).map((m) => {
                if (m.kind === 'beneficiary') {
                  const ben = (beneficiaries || []).find((bb) => bb.id === m.id);
                  return ben ? `${ben.first_name || ''} ${ben.last_name || ''}`.trim() : null;
                }
                if (m.kind === 'external_person') {
                  const ep = (data?.external_people || []).find((p) => p.id === m.id);
                  return ep ? `${ep.first_name || ''} ${ep.last_name || ''}`.trim() : null;
                }
                if (m.kind === 'user') {
                  return user ? `${user.first_name || ''} ${user.last_name || ''}`.trim() || 'You' : 'You';
                }
                return null;
              }).filter(Boolean);
              return (
                <div key={b.id} className="cfp-print-block-row" data-testid={`entity-print-block-row-${b.id}`}>
                  <div className="cfp-print-block-name">{b.name}</div>
                  <div className="cfp-print-block-line">
                    <span className="cfp-print-block-label">Members ({memberLabels.length}):</span>{' '}
                    {memberLabels.length === 0 ? '—' : memberLabels.join(', ')}
                  </div>
                  <div className="cfp-print-block-line">
                    <span className="cfp-print-block-label">Attached to ({attachedEntityNames.length}):</span>{' '}
                    {attachedEntityNames.length === 0 ? 'not attached to any entity yet' : attachedEntityNames.join(', ')}
                  </div>
                </div>
              );
            })}
          </div>
          <div className="cfp-print-footer">
            <span>Generated by CarryOn™</span>
            <span>carryon.us</span>
          </div>
        </div>
      )}
    </div>,
    document.body
  );
}

function truncate(s, n) {
  if (!s) return '';
  return s.length <= n ? s : s.slice(0, n - 1) + '…';
}
